"""Rebuild the app's front end from the team's design plus the live logic.

    python3 web/assemble.py /path/to/tenard/index.html [design-commit]

The team's prototype (github.com/hey-niia/tenard) is one HTML file: styles, icons and a scripted chat.
This takes its styles, icons and status bar, and swaps the scripted chat for web/live/live.js, which calls
the backend. Output: web/index.html and web/public/app.js. Edit web/live/, never the two output files.

When the design changes: pull their repo, read `git diff` for index.html, run this, then port any change
they made to a view or a card by hand into web/live/live.js (their CSS comes across on its own).
"""
import sys
from pathlib import Path

WEB = Path(__file__).resolve().parent


def main() -> None:
    src = Path(sys.argv[1]).read_text()
    commit = sys.argv[2] if len(sys.argv) > 2 else "unknown"
    head, rest = src.split("<script>\n", 1)
    script = rest.split("</script>", 1)[0]
    icons = script.split("/* ---------- problem types", 1)[0]
    type_icons = ("const TI = " + script.split("const TI = ", 1)[1].split("const PI = ", 1)[0]).split("const MOULD_RES", 1)[0]
    status_bar = "const STATUS_BAR = " + script.split("const STATUS_BAR = ", 1)[1].split("function openCount", 1)[0]
    head = head.replace("</style>", (WEB / "live/extra.css").read_text() + "</style>")
    (WEB / "index.html").write_text(
        head + '<script src="/app.js"></script>\n<a class="prooflink" href="/proof.html">How we tested it</a>\n</body>\n</html>\n')
    banner = ("/* Tenard: the app's front end. Design, icons and views from the team's prototype "
              f"(github.com/hey-niia/tenard,\n   commit {commit}); live logic below. Generated by web/assemble.py; "
              "edit web/live/live.js instead. */\n")
    (WEB / "public/app.js").write_text(banner + icons + type_icons + status_bar + (WEB / "live/live.js").read_text())
    print("wrote web/index.html and web/public/app.js")


if __name__ == "__main__":
    main()
